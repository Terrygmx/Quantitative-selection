"""Concrete tool executors behind the design-section-8 role boundaries.
Every tool works on injected read-only ports and a drafts directory:
research tools can only read data and write JSON drafts, data-quality
tools can only append quality events, and every research artifact
carries a research-not-advice disclaimer."""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Mapping

from quant_agent.ports.market_data import DataUnavailable, MarketDataPortLike
from quant_agent.ports.clock import Clock, SystemClock


DISCLAIMER = (
    "Research artifact generated by an agent; not investment advice and "
    "not a trade instruction."
)


class RoleToolbox:
    def __init__(
        self,
        data_port: MarketDataPortLike,
        drafts_dir: str | Path,
        quality_events_path: str | Path,
        clock: Clock = SystemClock(),
    ):
        self.data_port = data_port
        self.drafts_dir = Path(drafts_dir)
        self.quality_events_path = Path(quality_events_path)
        self.clock = clock

    def read_approved_dataset(self, symbol: str, as_of: datetime) -> Mapping[str, object]:
        try:
            bars = self.data_port.bars(symbol, as_of)
        except DataUnavailable as exc:
            return {
                "symbol": symbol,
                "error": "DATA_UNAVAILABLE",
                "reason_code": exc.event.reason_code,
            }
        return {
            "symbol": symbol,
            "as_of": as_of.isoformat(),
            "bars": [
                {
                    "timestamp": bar.timestamp.isoformat(),
                    "open": bar.open,
                    "high": bar.high,
                    "low": bar.low,
                    "close": bar.close,
                    "volume": bar.volume,
                }
                for bar in bars
            ],
        }

    def draft_experiment(
        self,
        strategy_id: str,
        config: Mapping[str, object],
        rationale: str,
    ) -> Path:
        """Write a JSON experiment draft; drafts are never production
        configs and require human promotion."""
        self.drafts_dir.mkdir(parents=True, exist_ok=True)
        stamp = self.clock.now().strftime("%Y%m%dT%H%M%S")
        path = self.drafts_dir / f"{strategy_id}-{stamp}.json"
        path.write_text(
            json.dumps(
                {
                    "strategy_id": strategy_id,
                    "config": dict(config),
                    "rationale": rationale,
                    "status": "draft",
                    "disclaimer": DISCLAIMER,
                    "created_at": self.clock.now().isoformat(),
                },
                ensure_ascii=False,
                indent=1,
            )
            + "\n",
            encoding="utf-8",
        )
        return path

    def create_quality_event(
        self, reason_code: str, symbol: str, message: str
    ) -> Path:
        """Append a quality event to the JSONL ledger (append-only)."""
        self.quality_events_path.parent.mkdir(parents=True, exist_ok=True)
        record = {
            "level": "warn",
            "reason_code": reason_code,
            "symbol": symbol,
            "message": message,
            "created_at": self.clock.now().isoformat(),
        }
        with self.quality_events_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")
        return self.quality_events_path

    def explain_signal(
        self, symbol: str, as_of: datetime, thesis: str
    ) -> Mapping[str, object]:
        dataset = self.read_approved_dataset(symbol, as_of)
        bars = dataset.get("bars", [])
        last_close: float | None = None
        if isinstance(bars, list) and bars:
            last_row = bars[-1]
            if isinstance(last_row, dict):
                close = last_row.get("close")
                if isinstance(close, (int, float)):
                    last_close = float(close)
        return {
            "symbol": symbol,
            "as_of": as_of.isoformat(),
            "last_close": last_close,
            "thesis": thesis,
            "disclaimer": DISCLAIMER,
        }

    def explain_rejection(
        self, reason_code: str, context: Mapping[str, object]
    ) -> Mapping[str, object]:
        return {
            "reason_code": reason_code,
            "context": dict(context),
            "explanation": REJECTION_EXPLANATIONS.get(
                reason_code,
                "Order rejected by the deterministic A-share rules layer; "
                "agents cannot override risk decisions.",
            ),
            "disclaimer": DISCLAIMER,
        }


REJECTION_EXPLANATIONS: dict[str, str] = {
    "T1_UNSETTLED": (
        "The shares being sold were bought today and have not settled; "
        "A-share T+1 settlement makes them unsellable until the next session."
    ),
    "LIMIT_UP": "The price is locked at limit-up: buy orders queue and cannot fill.",
    "LIMIT_DOWN": (
        "The price is locked at limit-down: sell orders queue and cannot fill."
    ),
    "SUSPENDED": "The instrument is suspended and accepts no orders.",
    "OUTSIDE_CONTINUOUS_AUCTION": (
        "The order timestamp is outside the continuous auction sessions "
        "(9:30-11:30, 13:00-15:00)."
    ),
    "INVALID_AFTER_HOURS_PRICE": (
        "After-hours fixed-price orders must respect the closing-price "
        "limit rule (SSE 2026 rules 3.7.5)."
    ),
    "INSUFFICIENT_CASH": "The slipped cost of the order exceeds available cash.",
    "INVALID_LOT": "Order quantity violates the 100-share lot rule.",
    "PRICE_BAND": "The limit price is outside the exchange price band.",
}
